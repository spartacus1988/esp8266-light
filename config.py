# -*- coding: utf-8 -*-
# ============================================================
#  config.py  —  все настройки прошивки в одном месте
#
#  Плата: Wemos D1 mini (ESP8266) + модуль реле
#  MicroPython: ESP8266_GENERIC v1.29.0 и новее
# ============================================================

# ------------------------------------------------------------
# Wi-Fi: своя точка доступа.
# К ней подключаетесь с телефона/ПК, чтобы управлять светом
# и чтобы загружать код по Wi-Fi (WebREPL).
# ------------------------------------------------------------
AP_SSID = "esp-light"           # имя сети Wi-Fi
AP_PASSWORD = "light1234"       # пароль сети, 8..63 символов (WPA2)

# ------------------------------------------------------------
# WebREPL — загрузка и правка кода по Wi-Fi (без USB-кабеля).
# Ограничение WebREPL: пароль от 4 до 9 символов!
# ------------------------------------------------------------
WEBREPL_PASSWORD = "esp8266"
WEBREPL_PORT = 8266

# ------------------------------------------------------------
# Пины Wemos D1 mini
# ------------------------------------------------------------
RELAY_PIN = 5       # D1  ->  контакт IN модуля реле
LED_PIN = 2         # D4  ->  встроенный светодиод платы

# ------------------------------------------------------------
# Логика модуля реле
#   True  — реле срабатывает от ВЫСОКОГО уровня (IN = HIGH -> включено)
#   False — реле срабатывает от НИЗКОГО уровня  (IN = LOW  -> включено)
# Если свет включается "наоборот" — переключите это значение.
# ------------------------------------------------------------
RELAY_ACTIVE_HIGH = True

# Встроенный светодиод D4 на D1 mini зажигается НИЗКИМ уровнем.
LED_ACTIVE_LOW = True

# ------------------------------------------------------------
# Веб-интерфейс
# ------------------------------------------------------------
HTTP_PORT = 80
DEVICE_NAME = "Свет"            # заголовок страницы управления

# ------------------------------------------------------------
# Автоуправление по АЦП (вход A0) — как в оригинальном проекте
#   True  — реле управляется напряжением на A0
#   False — только кнопками на странице
#
# Пока авто-режим включён, каждые AUTO_ADC_POLL_MS мс читается A0:
#   A0 >  AUTO_ADC_THRESHOLD -> свет ВКЛ
#   A0 <= AUTO_ADC_THRESHOLD -> свет ВЫКЛ
#
# Авто-режим выключается ТОЛЬКО по нажатию кнопки ВКЛ/ВЫКЛ на странице
# (просто открыть страницу его не отключает). Вернуть его можно кнопкой
# «АВТО» на странице или запросом /?mode=auto — без перезагрузки платы.
# ------------------------------------------------------------
AUTO_CONTROL = True             # включать авто-режим при старте
AUTO_ADC_THRESHOLD = 512        # порог 0..1023
AUTO_ADC_POLL_MS = 500          # период опроса A0, мс
